    on de.id = fv.eleicao_id

left join public.dim_uf uf
    on uf.id = fv.uf_id

join public.dim_candidato c
    on c.id = fv.candidato_id

left join public.dim_partido p
    on p.id = c.partido_id

group by
    de.ano,
    de.nome,
    de.ambiente,
    uf.sigla,
    c.cargo,
    c.numero,
    c.nome,
    p.sigla,
    p.nome;


-- ============================================================
-- 17. VIEW DE AUDITORIA
-- ============================================================

create or replace view public.vw_bi_auditoria as
select
    fa.id,

    de.ano,

    de.nome as eleicao,

    de.ambiente,

    uf.sigla as uf,

    mun.nome as municipio,

    z.numero as zona,

    s.numero as secao,

    fa.status,

    fa.total_bu,

    fa.total_resultado,

    fa.total_bu -
        fa.total_resultado
        as diferenca_total,

    fa.hash_calculado,

    fa.hash_armazenado,

    fa.criado_em

from public.fact_auditoria fa

left join public.dim_eleicao de
    on de.id = fa.eleicao_id

left join public.dim_secao s
    on s.id = fa.secao_id

left join public.dim_zona z
    on z.id = s.zona_id

left join public.dim_municipio mun
    on mun.id = z.municipio_id

left join public.dim_uf uf
    on uf.id = mun.uf_id;


-- ============================================================
-- 18. VIEW DE INGESTÃO
-- ============================================================

create or replace view public.vw_bi_ingestoes as
select
    i.id,

    de.ano,

    de.nome as eleicao,

    i.tipo_arquivo,

    i.url_origem,

    i.idg,

    i.sha256,

    i.iniciado_em,

    i.finalizado_em,

    i.status,

    i.registros_lidos,

    i.registros_gravados,

    i.erro

from public.ingestoes_tse i

left join public.dim_eleicao de
    on de.id = i.eleicao_id;


