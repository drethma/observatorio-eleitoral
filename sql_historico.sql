-- ============================================================
-- OBSERVATÓRIO ELEITORAL
-- MODELO HISTÓRICO TSE + POWER BI
--
-- Estratégia:
-- 1. Não apagar tabelas existentes.
-- 2. Criar uma camada dimensional.
-- 3. Criar fatos de votação.
-- 4. Preservar arquivos brutos do TSE.
-- 5. Preparar views para Power BI.
-- ============================================================


-- ============================================================
-- 1. ELEIÇÃO
-- ============================================================

create table if not exists public.dim_eleicao (
    id bigint generated by default as identity primary key,

    ano integer not null,

    codigo_tse text,

    nome text not null,

    tipo text,

    inicio date,

    fim date,

    ambiente text not null default 'oficial'
        check (
            ambiente in (
                'demo',
                'simulado',
                'oficial'
            )
        ),

    fonte text not null default 'TSE',

    criado_em timestamptz not null default now(),

    atualizado_em timestamptz not null default now(),

    unique (
        ano,
        codigo_tse,
        ambiente
    )
);


-- ============================================================
-- 2. PLEITO
-- ============================================================

create table if not exists public.dim_pleito (
    id bigint generated by default as identity primary key,

    eleicao_id bigint not null
        references public.dim_eleicao(id)
        on delete cascade,

    codigo_tse text,

    codigo_turno text,

    numero_turno integer,

    codigo_tipo text,

    nome text,

    cargo text,

    criado_em timestamptz not null default now(),

    unique (
        eleicao_id,
        codigo_tse
    )
);


-- ============================================================
-- 3. UF
-- ============================================================

create table if not exists public.dim_uf (
    id bigint generated by default as identity primary key,

    sigla text not null,

    nome text not null,

    codigo_tse text,

    codigo_ibge text,

    criado_em timestamptz not null default now(),

    unique (
        sigla
    ),

    unique (
        codigo_ibge
    )
);


-- ============================================================
-- 4. MUNICÍPIO
-- ============================================================

create table if not exists public.dim_municipio (
    id bigint generated by default as identity primary key,

    uf_id bigint not null
        references public.dim_uf(id)
        on delete restrict,

    codigo_tse text,

    codigo_ibge text,

    nome text not null,

    criado_em timestamptz not null default now(),

    unique (
        uf_id,
        codigo_ibge
    )
);


-- ============================================================
-- 5. ZONA
-- ============================================================

create table if not exists public.dim_zona (
    id bigint generated by default as identity primary key,

    municipio_id bigint not null
        references public.dim_municipio(id)
        on delete restrict,

    numero integer not null,

    criado_em timestamptz not null default now(),

    unique (
        municipio_id,
        numero
    )
);


-- ============================================================
-- 6. SEÇÃO
-- ============================================================

create table if not exists public.dim_secao (
    id bigint generated by default as identity primary key,

    zona_id bigint not null
        references public.dim_zona(id)
        on delete restrict,

    numero integer not null,

    localidade_id bigint,

    criado_em timestamptz not null default now(),

    unique (
        zona_id,
        numero
    )
);


-- ============================================================
-- 7. PARTIDO
-- ============================================================

create table if not exists public.dim_partido (
    id bigint generated by default as identity primary key,

    numero integer,

    sigla text,

    nome text not null,

    codigo_tse text,

    criado_em timestamptz not null default now(),

    atualizado_em timestamptz not null default now()
);


-- ============================================================
-- 8. CANDIDATO
-- ============================================================

create table if not exists public.dim_candidato (
    id bigint generated by default as identity primary key,

    eleicao_id bigint not null
        references public.dim_eleicao(id)
        on delete cascade,

    partido_id bigint
        references public.dim_partido(id)
        on delete restrict,

    numero integer not null,

    nome text,

    nome_urna text,

    cargo text,

    codigo_tse text,

    criado_em timestamptz not null default now(),

    unique (
        eleicao_id,
        numero,
        cargo
    )
);


-- ============================================================
-- 9. ARQUIVOS BRUTOS TSE
-- ============================================================

create table if not exists public.raw_arquivos_tse (
    id bigint generated by default as identity primary key,

    eleicao_id bigint
        references public.dim_eleicao(id)
        on delete restrict,

    pleito_id bigint
        references public.dim_pleito(id)
        on delete restrict,

    tipo_arquivo text not null,

    nome_arquivo text,

    url_origem text,

    idg text,

    etag text,

    last_modified text,

    sha256 text not null,

    conteudo_json jsonb not null,

    recebido_em timestamptz not null default now(),

    processado_em timestamptz,

    status text not null default 'recebido'
        check (
            status in (
                'recebido',
                'processando',
                'processado',
                'erro',
                'ignorado'
            )
        ),

    erro text,

    unique (
        sha256
    )
);


-- ============================================================
-- 10. FATO DE VOTAÇÃO
-- ============================================================

create table if not exists public.fact_votacao (
    id bigint generated by default as identity primary key,

    eleicao_id bigint not null
        references public.dim_eleicao(id)
        on delete restrict,

    pleito_id bigint
        references public.dim_pleito(id)
        on delete restrict,

    candidato_id bigint not null
        references public.dim_candidato(id)
        on delete restrict,

    uf_id bigint
        references public.dim_uf(id)
        on delete restrict,

    municipio_id bigint
        references public.dim_municipio(id)
        on delete restrict,

    zona_id bigint
        references public.dim_zona(id)
        on delete restrict,

    secao_id bigint
        references public.dim_secao(id)
        on delete restrict,

    raw_arquivo_id bigint
        references public.raw_arquivos_tse(id)
        on delete restrict,

    votos bigint not null default 0,

    percentual numeric(12,8),

    coletado_em timestamptz not null default now(),

    unique (
        eleicao_id,
        pleito_id,
        candidato_id,
        secao_id,
        raw_arquivo_id
    )
);


-- ============================================================
-- 11. FATO DE BOLETIM
-- ============================================================

create table if not exists public.fact_boletim (
    id bigint generated by default as identity primary key,

    eleicao_id bigint
        references public.dim_eleicao(id)
        on delete restrict,

    pleito_id bigint
        references public.dim_pleito(id)
        on delete restrict,

    secao_id bigint
        references public.dim_secao(id)
        on delete restrict,

    raw_arquivo_id bigint
        references public.raw_arquivos_tse(id)
        on delete restrict,

    arquivo text,

    sha256 text,

    total_votos bigint,

    status text,

    recebido_em timestamptz,

    criado_em timestamptz not null default now()
);


-- ============================================================
-- 12. AUDITORIA HISTÓRICA
-- ============================================================

create table if not exists public.fact_auditoria (
    id bigint generated by default as identity primary key,

    eleicao_id bigint
        references public.dim_eleicao(id)
        on delete restrict,

    pleito_id bigint
        references public.dim_pleito(id)
        on delete restrict,

    secao_id bigint
        references public.dim_secao(id)
        on delete restrict,

    boletim_id bigint
        references public.fact_boletim(id)
        on delete restrict,

    raw_arquivo_id bigint
        references public.raw_arquivos_tse(id)
        on delete restrict,

    status text not null,

    total_bu bigint,

    total_resultado bigint,

    divergencias jsonb not null default '[]'::jsonb,

    hash_calculado text,

    hash_armazenado text,

    criado_em timestamptz not null default now()
);


-- ============================================================
-- 13. INGESTÕES TSE
-- ============================================================

create table if not exists public.ingestoes_tse (
    id bigint generated by default as identity primary key,

    eleicao_id bigint
        references public.dim_eleicao(id)
        on delete restrict,

    tipo_arquivo text,

    url_origem text,

    idg text,

    etag text,

    last_modified text,

    sha256 text,

    iniciado_em timestamptz not null default now(),

    finalizado_em timestamptz,

    status text not null default 'iniciado'
        check (
            status in (
                'iniciado',
                'sucesso',
                'sem_alteracao',
                'erro'
            )
        ),

    registros_lidos integer default 0,

    registros_gravados integer default 0,

    erro text
);


