-- ============================================================
-- 14. VIEWS PARA POWER BI
-- ============================================================

create or replace view public.vw_bi_votacao as
select
    fv.id,

    de.ano,

    de.nome as eleicao,

    de.tipo as tipo_eleicao,

    de.ambiente,

    dp.nome as pleito,

    dp.numero_turno,

    uf.sigla as uf,

    uf.nome as estado,

    mun.nome as municipio,

    z.numero as zona,

    s.numero as secao,

    c.numero as numero_candidato,

    c.nome as candidato,

    c.nome_urna,

    c.cargo,

    p.sigla as partido_sigla,

    p.nome as partido,

    fv.votos,

    fv.percentual,

    fv.coletado_em

from public.fact_votacao fv

join public.dim_eleicao de
    on de.id = fv.eleicao_id

left join public.dim_pleito dp
    on dp.id = fv.pleito_id

left join public.dim_uf uf
    on uf.id = fv.uf_id

left join public.dim_municipio mun
    on mun.id = fv.municipio_id

left join public.dim_zona z
    on z.id = fv.zona_id

left join public.dim_secao s
    on s.id = fv.secao_id

join public.dim_candidato c
    on c.id = fv.candidato_id

left join public.dim_partido p
    on p.id = c.partido_id;


-- ============================================================
-- 15. VIEW DE RESULTADO MUNICIPAL
-- ============================================================

create or replace view public.vw_bi_resultado_municipio as
select
    de.ano,

    de.nome as eleicao,

    de.ambiente,

    uf.sigla as uf,

    mun.nome as municipio,

    c.cargo,

    c.numero as numero_candidato,

    c.nome as candidato,

    p.sigla as partido_sigla,

    p.nome as partido,

    sum(fv.votos) as votos

from public.fact_votacao fv

join public.dim_eleicao de
    on de.id = fv.eleicao_id

left join public.dim_uf uf
    on uf.id = fv.uf_id

left join public.dim_municipio mun
    on mun.id = fv.municipio_id

join public.dim_candidato c
    on c.id = fv.candidato_id

left join public.dim_partido p
    on p.id = c.partido_id

group by
    de.ano,
    de.nome,
    de.ambiente,
    uf.sigla,
    mun.nome,
    c.cargo,
    c.numero,
    c.nome,
    p.sigla,
    p.nome;


-- ============================================================
-- 16. VIEW DE RESULTADO ESTADUAL
-- ============================================================

create or replace view public.vw_bi_resultado_estado as
select
    de.ano,

    de.nome as eleicao,

    de.ambiente,

    uf.sigla as uf,

    c.cargo,

    c.numero as numero_candidato,

    c.nome as candidato,

    p.sigla as partido_sigla,

    p.nome as partido,

    sum(fv.votos) as votos

from public.fact_votacao fv

